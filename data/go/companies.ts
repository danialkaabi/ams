/** Even tier spread for owner-operators that manage their own tonnage in house. */
function tiers(
  fleet: number,
  overrides: Partial<Record<OwnershipTier, number>> = {},
): Record<OwnershipTier, number> {
  return {
    beneficialOwner: fleet,
    registeredOwner: fleet,
    commercialManager: fleet,
    operator: fleet,
    commerciallyControlled: fleet,
    technicalManager: fleet,
    ismManager: fleet,
    ...overrides,
  };
}

